/**
 * Split the markdown knowledge base into editable sections, one per "##"
 * heading. Used to seed the admin-editable Knowledge Base on first run.
 * @returns {Array<{title:string, content:string, order:number}>}
 */
function parseKnowledgeSections(md = KNOWLEDGE_BASE) {
  return md
    .split(/\n##\s+/)      // split on each "## Heading"
    .slice(1)              // drop the leading "# TITLE" chunk
    .map((chunk, i) => {
      const nl = chunk.indexOf("\n");
      const title = (nl === -1 ? chunk : chunk.slice(0, nl)).trim();
      const content = (nl === -1 ? "" : chunk.slice(nl + 1)).trim();
      return { title, content, order: i };
    })
    .filter((s) => s.title);
}

const KNOWLEDGE_SECTIONS = parseKnowledgeSections();

